<?php

/*
 * Generates the data object reference in README.md from the DTO classes.
 *
 * Descriptions come from docblocks, API field names from #[MapInputName] and
 * example values from tests/Fixtures/edition.json run through EditionData.
 *
 * Usage: composer docs
 */

require __DIR__.'/../vendor/autoload.php';

use Illuminate\Support\Str;
use Orchestra\Testbench\Foundation\Application;
use Spatie\LaravelData\Attributes\Computed;
use Spatie\LaravelData\Attributes\Hidden;
use Spatie\LaravelData\Attributes\MapInputName;
use Spatie\LaravelData\Data;
use Spatie\LaravelData\DataCollection;
use Spatie\LaravelData\LaravelDataServiceProvider;
use Wernersoderstrom\MockingbirdApiClient\Editions\AwardData;
use Wernersoderstrom\MockingbirdApiClient\Editions\BindingCodeData;
use Wernersoderstrom\MockingbirdApiClient\Editions\ContributorData;
use Wernersoderstrom\MockingbirdApiClient\Editions\ContributorRoleData;
use Wernersoderstrom\MockingbirdApiClient\Editions\CostCenterData;
use Wernersoderstrom\MockingbirdApiClient\Editions\EditionData;
use Wernersoderstrom\MockingbirdApiClient\Editions\LanguageData;
use Wernersoderstrom\MockingbirdApiClient\Editions\MainGroupData;
use Wernersoderstrom\MockingbirdApiClient\Editions\PriceData;
use Wernersoderstrom\MockingbirdApiClient\Editions\SeasonData;
use Wernersoderstrom\MockingbirdApiClient\Editions\StockBalanceData;
use Wernersoderstrom\MockingbirdApiClient\Editions\SubGroupData;
use Wernersoderstrom\MockingbirdApiClient\Editions\TextData;

const README = __DIR__.'/../README.md';
const START_MARKER = '<!-- data-objects:start -->';
const END_MARKER = '<!-- data-objects:end -->';

Application::create()->register(LaravelDataServiceProvider::class);

$fixtures = __DIR__.'/../tests/Fixtures';
$edition = EditionData::from([
    ...json_decode((string) file_get_contents("{$fixtures}/edition.json"), true),
    'work' => json_decode((string) file_get_contents("{$fixtures}/work.json"), true),
]);

// The author is used as the example contributor, so staff names stay out of the docs
$author = $edition->contributors->toCollection()->firstWhere('role.name', 'Author');

/** @var array<class-string<Data>, Data|null> $examples */
$examples = [
    EditionData::class => $edition,
    BindingCodeData::class => $edition->bindingCode,
    ContributorData::class => $author,
    ContributorRoleData::class => $author?->role,
    CostCenterData::class => $edition->costCenter,
    SeasonData::class => $edition->season,
    PriceData::class => $edition->prices->toCollection()->first(),
    LanguageData::class => $edition->languages->toCollection()->first(),
    MainGroupData::class => $edition->mainGroup,
    SubGroupData::class => $edition->subGroup,
    AwardData::class => $edition->awards->toCollection()->first(),
    TextData::class => $edition->texts->toCollection()->first(),
    StockBalanceData::class => new StockBalanceData(gtin: (int) $edition->gtin, balance: 10),
];

$sections = [
    'Generated by `composer docs` from the DTO classes, with example values from the public edition in `tests/Fixtures/edition.json`. Do not edit by hand.',
];

foreach ($examples as $class => $example) {
    $sections[] = classSection($class, $example);
}

$sections[] = jsonExample($edition, $author);

$readme = (string) file_get_contents(README);
$pattern = '/'.preg_quote(START_MARKER, '/').'.*?'.preg_quote(END_MARKER, '/').'/s';

if (preg_match($pattern, $readme) !== 1) {
    fwrite(STDERR, 'Markers '.START_MARKER.' and '.END_MARKER." not found in README.md\n");
    exit(1);
}

file_put_contents(README, preg_replace_callback(
    $pattern,
    fn () => START_MARKER."\n\n".implode("\n\n", $sections)."\n\n".END_MARKER,
    $readme
));

echo "README.md updated\n";

/**
 * @param  class-string<Data>  $class
 */
function classSection(string $class, ?Data $example): string
{
    $reflection = new ReflectionClass($class);
    $params = paramDocs((string) $reflection->getConstructor()?->getDocComment());
    $values = $example?->toArray() ?? [];

    $properties = [];
    $computed = [];

    foreach ($reflection->getProperties(ReflectionProperty::IS_PUBLIC) as $property) {
        if ($property->getDeclaringClass()->getName() !== $class || $property->getAttributes(Hidden::class) !== []) {
            continue;
        }

        $name = $property->getName();

        $row = sprintf(
            '| `%s` | `%s` | %s | %s |',
            $name,
            cell(normalizeType($params[$name]['type'] ?? (string) $property->getType())),
            exampleValue($example !== null ? $example->{$name} : null, $values[$name] ?? null, $example === null),
            cell(description($property, $params[$name]['description'] ?? '')),
        );

        // Computed properties are listed after the ones read from the API
        if ($property->getAttributes(Computed::class) !== []) {
            $computed[] = $row;
        } else {
            $properties[] = $row;
        }
    }

    $rows = [
        '### '.$reflection->getShortName(),
        '',
        '| Property | Type | Example | Description |',
        '|---|---|---|---|',
        ...$properties,
        ...$computed,
    ];

    $methods = methodRows($reflection);

    if ($methods !== []) {
        array_push($rows, '', '| Method | Description |', '|---|---|', ...$methods);
    }

    return implode("\n", $rows);
}

/**
 * @param  ReflectionClass<Data>  $reflection
 * @return list<string>
 */
function methodRows(ReflectionClass $reflection): array
{
    $rows = [];

    foreach ($reflection->getMethods(ReflectionMethod::IS_PUBLIC) as $method) {
        // Constructors, factories and internal resolve* helpers are not part of the documented API
        if ($method->getDeclaringClass()->getName() !== $reflection->getName()
            || $method->isStatic()
            || $method->isConstructor()
            || str_starts_with($method->getName(), 'resolve')) {
            continue;
        }

        $rows[] = sprintf(
            '| `%s(): %s` | %s |',
            $method->getName(),
            cell(normalizeType((string) $method->getReturnType())),
            cell(summary((string) $method->getDocComment())),
        );
    }

    return $rows;
}

function description(ReflectionProperty $property, string $paramDescription): string
{
    $parts = [];

    if ($property->getAttributes(Computed::class) !== []) {
        $parts[] = '*Computed*';
    }

    $mapped = ($property->getAttributes(MapInputName::class)[0] ?? null)?->getArguments()[0] ?? null;

    if (is_string($mapped) && $mapped !== $property->getName()) {
        $parts[] = 'From `'.$mapped.'`';
    }

    $parts[] = $paramDescription !== '' ? $paramDescription : summary((string) $property->getDocComment());

    return implode('. ', array_filter(array_map(fn (string $part) => rtrim($part, '. '), $parts)));
}

function exampleValue(mixed $value, mixed $serialized, bool $noExample): string
{
    if ($noExample) {
        return '';
    }

    return match (true) {
        $value === null => '`null`',
        is_bool($value) => $value ? '`true`' : '`false`',
        $value instanceof DataCollection => $value->count() > 0
            ? 'list of '.classLink(get_class($value->toCollection()->first()))
            : '`[]`',
        $value instanceof Data => classLink(get_class($value)),
        is_array($value) => '`'.cell(Str::limit((string) json_encode(array_slice($value, 0, 3), JSON_UNESCAPED_UNICODE), 60)).'`',
        default => '`'.cell(Str::limit(strip_tags(is_scalar($serialized) ? (string) $serialized : (string) json_encode($serialized)), 60)).'`',
    };
}

function jsonExample(EditionData $edition, ?ContributorData $author): string
{
    $data = $edition->toArray();

    // Keep one item per list so the example stays readable
    foreach ($data as $key => $value) {
        if (is_array($value) && array_is_list($value) && count($value) > 1) {
            $data[$key] = array_slice($value, 0, 1);
        }
    }

    $data['contributors'] = $author !== null ? [$author->toArray()] : [];

    array_walk_recursive($data, function (mixed &$value): void {
        if (is_string($value)) {
            $value = Str::limit($value, 80);
        }
    });

    return implode("\n", [
        '### Example',
        '',
        '<details>',
        '<summary><code>$edition->toArray()</code>, lists shortened to one item</summary>',
        '',
        '```json',
        (string) json_encode($data, JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE),
        '```',
        '',
        '</details>',
    ]);
}

/**
 * @return array<string, array{type: string, description: string}>
 */
function paramDocs(string $docComment): array
{
    preg_match_all('/@param\s+(.+?)\s+\$(\w+)(?:[ \t]+(.*))?$/m', $docComment, $matches, PREG_SET_ORDER);

    $params = [];

    foreach ($matches as $match) {
        $params[$match[2]] = ['type' => shortType($match[1]), 'description' => trim($match[3] ?? '')];
    }

    return $params;
}

function summary(string $docComment): string
{
    $lines = [];

    foreach (preg_split('/\R/', $docComment) ?: [] as $line) {
        $line = trim(preg_replace('#^\s*(/\*\*|\*/|\*)#', '', $line) ?? '');
        $line = trim(preg_replace('#\*/$#', '', $line) ?? '');

        if (str_starts_with($line, '@')) {
            break;
        }

        if ($line !== '') {
            $lines[] = $line;
        }
    }

    return implode(' ', $lines);
}

/**
 * Short class names and `?Type` for nullable single types, so docblock and native types look the same.
 */
function normalizeType(string $type): string
{
    $type = shortType($type);

    return preg_replace('/^(?:([\w]+)\|null|null\|([\w]+))$/', '?$1$2', $type) ?? $type;
}

function shortType(string $type): string
{
    return preg_replace('/(?:\\\\?[A-Za-z_][A-Za-z0-9_]*\\\\)+([A-Za-z_][A-Za-z0-9_]*)/', '$1', $type) ?? $type;
}

function classLink(string $class): string
{
    $name = class_basename($class);

    return '['.$name.'](#'.strtolower($name).')';
}

function cell(string $text): string
{
    return str_replace(['|', "\n"], ['\|', ' '], $text);
}
